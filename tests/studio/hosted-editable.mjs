/** Independent acceptance of the public editor and portable file. All input is local fixture data. */
import { chromium } from '@playwright/test';
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import { catalogSeed } from '../../public/ocp-studio/catalog-seed.mjs';
const out = '.studio-evidence/published';
await mkdir(out, { recursive: true });
const checks = [], errors = [];
const pass = name => checks.push({ name, passed: true });
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('https://plus-minus-g-yz0d1s.v2.appdeploy.ai/', { waitUntil: 'networkidle' });
  await page.getByRole('link', { name: /OCP 편집 열기/ }).click();
  await page.getByRole('button', { name: '＋ 원문', exact: true }).waitFor();
  assert.match(await page.locator('#env').innerText(), /브라우저/);
  pass('Public Plmag homepage opens its real editable OCP workspace');
  await page.getByRole('button', { name: '＋ 원문', exact: true }).click();
  await page.locator('input[name=title]').fill('Hosted acceptance source');
  await page.locator('textarea[name=body]').fill('Published editor fixture: preserve source then design and compile.');
  await page.getByRole('button', { name: '확인 · 기록', exact: true }).click();
  await page.getByRole('button', { name: '2차 분류', exact: true }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('textbox', { name: '캔버스 검색', exact: true }).fill('Hosted acceptance source');
  await page.locator('[data-select]').first().click();
  await page.getByRole('button', { name: '2차 분류', exact: true }).waitFor();
  pass('Public-origin note and original body survive refresh');
  await page.getByRole('button', { name: '2차 분류', exact: true }).click();
  await page.locator('textarea[name=rationale]').fill('Source and design acceptance fixture');
  await page.getByRole('button', { name: '확인 · 기록', exact: true }).click();
  await page.getByRole('button', { name: '승격 검토', exact: true }).click();
  await page.locator('select[name=parentId]').selectOption('product:ocp');
  await page.locator('input[name=targetTitle]').fill('Hosted working page');
  await page.locator('textarea[name=rationale]').fill('Reviewed fixture requirement');
  await page.locator('textarea[name=acceptance]').fill('Show heading and working detail anchor');
  await page.locator('input[name=approve]').check();
  await page.getByRole('button', { name: '확인 · 기록', exact: true }).click();
  await page.getByRole('button', { name: '승인 적용', exact: true }).click();
  await page.getByRole('button', { name: '디자인 설계', exact: true }).click();
  await page.locator('input[name=heading]').fill('A working published editor');
  await page.locator('textarea[name=body]').fill('This HTML is generated by the original OCP engine.');
  await page.locator('input[name=cta]').fill('Read details');
  await page.getByRole('button', { name: '확인 · 기록', exact: true }).click();
  await page.getByRole('button', { name: '디자인 → 코드', exact: true }).click();
  await page.getByRole('button', { name: '화면 실행', exact: true }).click();
  const frame = page.frameLocator('iframe[title="HTML 실행 화면"]');
  await frame.getByRole('heading', { name: 'A working published editor', exact: true }).waitFor();
  assert.equal(await frame.getByRole('link', { name: 'Read details' }).getAttribute('href'), '#details');
  await page.screenshot({ path: out + '/public-generated-screen.png' });
  await page.locator('.workbench-dialog [data-dismiss]').click();
  pass('On public host, classification→approval→apply→design→HTML actually runs');
  const nextDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'HTML 내려받기', exact: true }).click();
  const download = await nextDownload;
  assert.ok((await readFile(await download.path(), 'utf8')).includes('A working published editor'));
  pass('Public editor downloads generated HTML bytes');
  if (await page.locator('[data-action=close-panel]').isVisible()) await page.locator('[data-action=close-panel]').click();
  await page.locator('.stage').click({ position: { x: 500, y: 300 } });
  await page.keyboard.press('3');
  assert.ok((await page.locator('[data-action=journey]').getAttribute('class')).includes('active'));
  await page.screenshot({ path: out + '/public-editor.png' });
  pass('Public editor numeric shortcut works in its isolated UI');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: out + '/public-mobile.png' });
  await page.getByRole('link', { name: '← 플마지 홈', exact: true }).click();
  await page.getByRole('link', { name: /OCP 편집 열기/ }).waitFor();
  pass('Mobile back navigation returns to preserved Plmag homepage');

  const bundled = await build({ entryPoints: ['public/ocp-studio/workbench.mjs'], bundle: true, format: 'iife', globalName: 'OCPWorkspace', write: false, target: 'es2022' });
  const styles = (await readFile('public/ocp-studio/style.css', 'utf8')) + '\n' + (await readFile('public/ocp-studio/workbench.css', 'utf8'));
  const source = bundled.outputFiles[0].text.replaceAll('</script', '<\\/script');
  const html = '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><style>body{margin:0}' + styles + '</style><div id="workspace"></div><script>' + source + '\nOCPWorkspace.mountWorkbench(document.getElementById("workspace"),{seed:' + JSON.stringify(catalogSeed).replaceAll('<', '\\u003c') + ',storageName:"portable-fixture"}).then(x=>window.workbench=x);</script>';
  const filename = path.resolve(out, 'portable-fixture.html');
  await writeFile(filename, html);
  const portable = await context.newPage();
  portable.on('pageerror', e => errors.push(e.message));
  await portable.goto(pathToFileURL(filename).href);
  await portable.getByRole('button', { name: '＋ 원문', exact: true }).click();
  await portable.locator('input[name=title]').fill('Portable file source');
  await portable.locator('textarea[name=body]').fill('Stored from a real standalone file URL.');
  await portable.getByRole('button', { name: '확인 · 기록', exact: true }).click();
  await portable.getByRole('button', { name: '2차 분류', exact: true }).waitFor();
  await portable.reload();
  await portable.getByRole('textbox', { name: '캔버스 검색', exact: true }).fill('Portable file source');
  await portable.locator('[data-select]').first().click();
  await portable.getByRole('button', { name: '2차 분류', exact: true }).waitFor();
  pass('Real file:// standalone editor captures and persists source across reload');
  assert.equal(errors.length, 0, errors.join('\n'));
  pass('No uncaught JavaScript errors on public or standalone runtime');
  await writeFile(out + '/report.json', JSON.stringify({ sourceRevision: process.env.GITHUB_SHA, publicURL: 'https://plus-minus-g-yz0d1s.v2.appdeploy.ai/#/studio', scope: 'public editor + standalone file; private test browser storage only; no production REP data', checks, errors }, null, 2));
} catch (error) {
  await writeFile(out + '/report.json', JSON.stringify({ checks, errors, failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
